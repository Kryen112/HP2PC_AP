"""Generate mod/HPArchipelago/Classes/APMarkerClassTable.uc.

The table names every APCardMarker_WC<Name> and APContainerMarker_<Slot> class
as a literal, which keeps them loaded for as long as the package is. The
engine restores a spawned actor from a level's saved state only when its class
is already in memory, so a class that is only ever loaded by name can drop
out between visits and the saved marker is silently skipped.

Run after adding or removing a card marker or container token class:
    py -3.12 tools/gen_marker_class_table.py
"""
import re
from pathlib import Path

CLASSES = Path(__file__).resolve().parent.parent / "mod" / "HPArchipelago" / "Classes"
OUT = CLASSES / "APMarkerClassTable.uc"


def card_markers():
    table = {}
    for path in sorted(CLASSES.glob("APCardMarker_WC*.uc")):
        match = re.search(r"CardLocationId=(\d+)", path.read_text(encoding="latin-1"))
        if match:
            table[int(match.group(1))] = path.stem
    return table


def container_tokens():
    table = {}
    for path in sorted(CLASSES.glob("APContainerMarker_*.uc")):
        suffix = path.stem.rsplit("_", 1)[1]
        if suffix.isdigit():
            table[int(suffix)] = path.stem
    return table


def switch_body(table, cast):
    lines = ["    switch (id)", "    {"]
    for key in sorted(table):
        lines.append(f"        case {key}: return {cast}'{table[key]}';")
    lines.append("    }")
    lines.append("    return None;")
    return "\n".join(lines)


def main():
    cards = card_markers()
    tokens = container_tokens()
    text = f"""// Literal references to every card marker and container token class. A class
// named here stays loaded with the package, which the engine needs to rebuild a
// spawned marker from a level's saved state. Generated by
// tools/gen_marker_class_table.py. Regenerate it instead of editing by hand.
class APMarkerClassTable extends Object;

// The marker class for a card location id (1..101), or None.
static function class<APCardMarker> CardMarkerClass(int id)
{{
{switch_body(cards, "class")}
}}

// The token class for a container location slot (apId minus the location base),
// or None.
static function class<APContainerMarker> ContainerTokenClass(int id)
{{
{switch_body(tokens, "class")}
}}
"""
    OUT.write_text(text.replace("\n", "\r\n"), encoding="latin-1", newline="")
    print(f"wrote {OUT.name}: {len(cards)} card markers, {len(tokens)} container tokens")


if __name__ == "__main__":
    main()
